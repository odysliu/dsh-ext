#!/usr/bin/env python3
"""Generate the on-device CJK bitmap font.

The StopWatch draws text itself, so the glyphs live in flash as a 2-bit
grayscale atlas (4 levels, 28x28 cells). Coverage is GB2312 level 1 (the 3755
most common hanzi) plus punctuation plus printable ASCII, which is enough for
every prompt the bridge can produce.

Usage:
    python3 tools/genfont.py --font tools/.cache/fonts/NotoSansSC-Regular.otf \
        --out firmware/stopwatch/src/assets/font_cn.h

The generated header is committed, so a normal build does not need Python.
"""

from __future__ import annotations

import argparse
import pathlib
import struct

from PIL import Image, ImageDraw, ImageFont

CELL_W = 28
CELL_H = 28
ASCII_W = 18
ASCII_SIZE = 18
BASELINE = 23
LEVELS = 4
BYTES_PER_ROW = CELL_W * 2 // 8  # 2 bits per pixel
GLYPH_BYTES = BYTES_PER_ROW * CELL_H

EXTRA = "·—…‘’“”《》【】（）！？：；、，。￥·"


def gb2312_chars() -> list[str]:
    """GB2312 level-1 hanzi: the 3755 characters everyday text needs."""
    chars: list[str] = []
    for high in range(0xB0, 0xD8):
        for low in range(0xA1, 0xFF):
            try:
                chars.append(bytes([high, low]).decode("gb2312"))
            except UnicodeDecodeError:
                continue
    return chars


def render_cell(font: ImageFont.FreeTypeFont, char: str, width: int) -> Image.Image:
    image = Image.new("L", (width, CELL_H), 0)
    draw = ImageDraw.Draw(image)
    draw.text((0, BASELINE), char, font=font, fill=255, anchor="ls")
    return image


def pack(image: Image.Image) -> bytes:
    """Pack an 8-bit cell into 2-bit rows, most significant pixel first."""
    pixels = image.load()
    data = bytearray()
    quantum = 255 // (LEVELS - 1)
    for y in range(CELL_H):
        row = bytearray()
        byte = 0
        bits = 0
        for x in range(CELL_W):
            level = min(LEVELS - 1, (pixels[x, y] + quantum // 2) // quantum) if x < image.width else 0
            byte = (byte << 2) | level
            bits += 2
            if bits == 8:
                row.append(byte)
                byte = 0
                bits = 0
        data.extend(row)
    return bytes(data)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--font", required=True, help="path to NotoSansSC-Regular.otf")
    parser.add_argument("--out", required=True, help="generated header")
    parser.add_argument("--size", type=int, default=CELL_H)
    parser.add_argument("--preview", help="optional PNG preview path")
    args = parser.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    ascii_font = ImageFont.truetype(args.font, ASCII_SIZE)
    chars = set(gb2312_chars())
    chars.update(chr(code) for code in range(0x20, 0x7F))
    chars.update(EXTRA)
    ordered = sorted(chars, key=ord)

    widest = max(ascii_font.getlength(chr(code)) for code in range(0x20, 0x7F))
    if widest > ASCII_W:
        print(f"warning: widest ASCII glyph is {widest:.1f}px, wider than the {ASCII_W}px cell")

    glyphs: list[bytes] = []
    for char in ordered:
        if ord(char) < 0x80:
            glyphs.append(pack(render_cell(ascii_font, char, ASCII_W)))
        else:
            glyphs.append(pack(render_cell(font, char, CELL_W)))

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as handle:
        handle.write("// Generated by tools/genfont.py from Noto Sans SC (SIL OFL 1.1). Do not edit.\n")
        handle.write("#pragma once\n\n#include <stdint.h>\n\n")
        handle.write(f"#define FONT_CELL_W {CELL_W}\n")
        handle.write(f"#define FONT_CELL_H {CELL_H}\n")
        handle.write(f"#define FONT_ASCII_W {ASCII_W}\n")
        handle.write(f"#define FONT_GLYPH_BYTES {GLYPH_BYTES}\n")
        handle.write(f"#define FONT_GLYPH_COUNT {len(ordered)}\n\n")
        handle.write("static const uint16_t FONT_CODEPOINTS[FONT_GLYPH_COUNT] = {\n")
        for index in range(0, len(ordered), 16):
            chunk = ", ".join(f"0x{ord(char):04X}" for char in ordered[index : index + 16])
            handle.write(f"  {chunk},\n")
        handle.write("};\n\n")
        handle.write("static const uint8_t FONT_GLYPHS[FONT_GLYPH_COUNT][FONT_GLYPH_BYTES] = {\n")
        for glyph in glyphs:
            handle.write("  {" + ",".join(f"{byte:d}" for byte in glyph) + "},\n")
        handle.write("};\n")

    size_kb = out.stat().st_size / 1024
    print(f"glyphs={len(ordered)} bytes={len(glyphs) * GLYPH_BYTES} header={size_kb:.0f} KiB -> {out}")

    if args.preview:
        sample = "需要确认\n命令 npm run build\n需要完全权限：写工作区\n以外的临时文件"
        preview = Image.new("L", (466, 220), 0)
        draw = ImageDraw.Draw(preview)
        y = 6
        for line in sample.split("\n"):
            x = 8
            for char in line:
                if ord(char) < 0x80:
                    width = ASCII_W
                    cell = render_cell(ascii_font, char, ASCII_W)
                else:
                    width = CELL_W
                    cell = render_cell(font, char, CELL_W)
                preview.paste(cell, (x, y))
                x += width
            y += 34
        preview.resize((preview.width * 2, preview.height * 2), Image.NEAREST).save(args.preview)
        print(f"preview -> {args.preview}")


if __name__ == "__main__":
    main()
