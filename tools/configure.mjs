#!/usr/bin/env node
/**
 * Write firmware/stopwatch/src/secrets.h from the command line.
 *
 *   node tools/configure.mjs --ssid "home" --password "secret"
 *   node tools/configure.mjs --ssid "home" --password "secret" --token abc123 --port 47777
 */

import { writeFileSync, existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import process from 'node:process'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const TARGET = join(ROOT, 'firmware', 'stopwatch', 'src', 'secrets.h')

const args = parseArgs(process.argv.slice(2))
if (args.help !== undefined || args.ssid === undefined) {
  console.log(`usage: node tools/configure.mjs --ssid <name> --password <pass> [--token <t>] [--port 47777]

Writes firmware/stopwatch/src/secrets.h (git-ignored) and leaves everything else untouched.

  --host 192.168.0.123   skip UDP discovery and connect straight to this host
  --host-mac fc:b2:...   pin the host MAC when the router proxy-ARPs it`)
  process.exit(args.help !== undefined ? 0 : 1)
}

const ssid = String(args.ssid)
const password = String(args.password ?? '')
const port = Number(args.port ?? 47777)
const discoveryPort = Number(args.discoveryPort ?? 47778)
const token = String(args.token ?? '')
const hostIp = String(args.host ?? '')
const hostMac = String(args['host-mac'] ?? '')

if (ssid.trim() === '') fail('--ssid must not be empty')
if (!Number.isInteger(port) || port < 1 || port > 65535) fail('--port must be an integer in [1, 65535]')
if (!Number.isInteger(discoveryPort) || discoveryPort < 1 || discoveryPort > 65535) fail('--discoveryPort must be an integer')

const body = `// Generated by tools/configure.mjs — git-ignored, safe to edit by hand.
#pragma once

#define STOPWATCH_WIFI_SSID ${quote(ssid)}
#define STOPWATCH_WIFI_PASS ${quote(password)}

#define STOPWATCH_HOST_PORT ${port}
#define STOPWATCH_DISCOVERY_PORT ${discoveryPort}
#define STOPWATCH_HOST_TOKEN ${quote(token)}
#define STOPWATCH_HOST_IP ${quote(hostIp)}
#define STOPWATCH_HOST_MAC ${quote(hostMac)}
`
const previous = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
writeFileSync(TARGET, body, 'utf8')
console.log(`${previous === '' ? 'created' : 'updated'} ${TARGET}`)
console.log(`  ssid=${ssid} port=${port} discovery=${discoveryPort} token=${token === '' ? '(none)' : 'set'}`)
console.log(`  host=${hostIp === '' ? '(UDP discovery)' : hostIp}`)
console.log('\nNext: node tools/flash.mjs --port <serial port>')

/**
 * C string literal escaping for a value that came from a shell.
 * @param {string} value - raw text.
 * @returns {string} a quoted literal.
 */
function quote(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
}

/**
 * Print a usage error and exit.
 * @param {string} message - what went wrong.
 */
function fail(message) {
  console.error(`configure: ${message}`)
  process.exit(1)
}

/**
 * Tiny `--key value` parser.
 * @param {string[]} argv - arguments.
 * @returns {Record<string, string>} options.
 */
function parseArgs(argv) {
  const out = {}
  for (let index = 0; index < argv.length; index += 1) {
    const value = argv[index]
    if (!value.startsWith('--')) continue
    const next = argv[index + 1]
    if (next === undefined || next.startsWith('--')) {
      out[value.slice(2)] = ''
    } else {
      out[value.slice(2)] = next
      index += 1
    }
  }
  return out
}
