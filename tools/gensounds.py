#!/usr/bin/env python3
"""Generate the three UI sounds as WAV byte arrays for the firmware.

M5.Speaker.playWav() takes a complete WAV file, so the header is embedded
too. Mono 44.1 kHz / 16-bit keeps the decoder path simple.

Usage:
    python3 tools/gensounds.py --out firmware/stopwatch/src/assets/sounds.h
"""

from __future__ import annotations

import argparse
import io
import math
import pathlib
import struct
import wave

RATE = 44100
AMPLITUDE = 0.32


def tone(freq: float, seconds: float, fade: float = 0.6, shape: str = "sine", sweep: float = 0.0) -> list[float]:
    """One decaying note; `sweep` bends the pitch over the note."""
    total = int(RATE * seconds)
    samples = []
    phase = 0.0
    for index in range(total):
        t = index / total
        f = freq * (1.0 + sweep * t)
        phase += 2 * math.pi * f / RATE
        value = math.sin(phase)
        if shape == "square":
            value = 0.6 if value >= 0 else -0.6
        elif shape == "triangle":
            value = 2 / math.pi * math.asin(math.sin(phase))
        envelope = math.exp(-t / fade)
        attack = min(1.0, index / (RATE * 0.004))
        samples.append(value * envelope * attack)
    return samples


def silence(seconds: float) -> list[float]:
    return [0.0] * int(RATE * seconds)


def wav_bytes(samples: list[float]) -> bytes:
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(RATE)
        frames = bytearray()
        for sample in samples:
            clamped = max(-1.0, min(1.0, sample * AMPLITUDE))
            frames += struct.pack("<h", int(clamped * 32767))
        handle.writeframes(bytes(frames))
    return buffer.getvalue()


def build() -> dict[str, bytes]:
    alert = tone(880, 0.16, fade=0.35) + silence(0.03) + tone(1174.66, 0.30, fade=0.45)
    allow = tone(659.25, 0.09, fade=0.5) + tone(880, 0.09, fade=0.5) + tone(1174.66, 0.22, fade=0.6)
    deny = tone(220, 0.28, fade=0.5, shape="triangle", sweep=-0.25)
    return {"ALERT": wav_bytes(alert), "ALLOW": wav_bytes(allow), "DENY": wav_bytes(deny)}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    sounds = build()
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8") as handle:
        handle.write("// Generated by tools/gensounds.py. Do not edit.\n")
        handle.write("#pragma once\n\n#include <stdint.h>\n\n")
        for name, data in sounds.items():
            handle.write(f"static const uint8_t SOUND_{name}[{len(data)}] = {{\n")
            for offset in range(0, len(data), 24):
                chunk = ",".join(str(byte) for byte in data[offset : offset + 24])
                handle.write(f"  {chunk},\n")
            handle.write("};\n\n")
    total = sum(len(data) for data in sounds.values())
    print(f"sounds={len(sounds)} bytes={total} -> {out}")


if __name__ == "__main__":
    main()
